// Optional fallback text models, used only when OpenAI text generation fails (no credits, outage, rate limit) AND a key for
// the fallback is configured. Nothing changes for a setup that only has an OpenAI key.
//   ANTHROPIC_API_KEY  -> Claude  (model: ANTHROPIC_TEXT_MODEL, default claude-sonnet-5-5)
//   GEMINI_API_KEY     -> Gemini  (model: GEMINI_TEXT_MODEL, default gemini-2.5-flash)
//   TEXT_FALLBACK_ORDER = comma list, default "anthropic,gemini"
// Keys travel in headers, never in URLs.

export type FallbackId = "anthropic" | "gemini";

export function fallbackOrder(): FallbackId[] {
  const raw = (process.env.TEXT_FALLBACK_ORDER || "anthropic,gemini").split(",").map((s) => s.trim().toLowerCase());
  return raw.filter((s): s is FallbackId => (s === "anthropic" && !!process.env.ANTHROPIC_API_KEY) || (s === "gemini" && !!process.env.GEMINI_API_KEY));
}

/** True for failures a different provider could fix: no credits, bad or exhausted key, rate limit, server errors, network. */
export function isProviderFailure(e: any): boolean {
  const status = Number(e?.status ?? e?.response?.status);
  if (Number.isFinite(status) && status > 0) return [401, 402, 403, 429].includes(status) || status >= 500;
  const msg = String(e?.message || e);
  return /ECONN|ETIMEDOUT|ENOTFOUND|fetch failed|network|socket|timeout/i.test(msg);
}

async function post(url: string, headers: Record<string, string>, body: unknown): Promise<any> {
  const r = await fetch(url, { method: "POST", headers: { "Content-Type": "application/json", ...headers }, body: JSON.stringify(body) });
  const text = await r.text();
  if (!r.ok) throw Object.assign(new Error(`${url.split("/")[2]} ${r.status}: ${text.slice(0, 200)}`), { status: r.status });
  return JSON.parse(text);
}

async function viaAnthropic(system: string, user: string): Promise<string> {
  const j = await post(
    "https://api.anthropic.com/v1/messages",
    { "x-api-key": process.env.ANTHROPIC_API_KEY as string, "anthropic-version": "2023-06-01" },
    { model: process.env.ANTHROPIC_TEXT_MODEL || "claude-sonnet-5-5", max_tokens: 8000, system, messages: [{ role: "user", content: user }] }
  );
  const text = (j?.content ?? []).filter((b: any) => b?.type === "text").map((b: any) => b.text).join("");
  if (!text) throw new Error("Claude returned no text");
  return text.trim();
}

async function viaGemini(system: string, user: string): Promise<string> {
  const model = process.env.GEMINI_TEXT_MODEL || "gemini-2.5-flash";
  const j = await post(
    `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(model)}:generateContent`,
    { "x-goog-api-key": process.env.GEMINI_API_KEY as string },
    { systemInstruction: { parts: [{ text: system }] }, contents: [{ role: "user", parts: [{ text: user }] }] }
  );
  const text = (j?.candidates?.[0]?.content?.parts ?? []).map((p: any) => p?.text ?? "").join("");
  if (!text) throw new Error("Gemini returned no text");
  return text.trim();
}

/** Tries each configured fallback in order; throws the last error (or null when none is configured). */
export async function generateWithFallback(system: string, user: string, log?: (msg: string) => void): Promise<{ text: string; provider: FallbackId } | null> {
  const order = fallbackOrder();
  if (!order.length) return null;
  let last: unknown = null;
  for (const id of order) {
    try {
      const text = id === "anthropic" ? await viaAnthropic(system, user) : await viaGemini(system, user);
      log?.(`text generated by fallback provider ${id}`);
      return { text, provider: id };
    } catch (e) {
      last = e;
    }
  }
  throw last;
}
