// Command-line driver for making a video from a plan file.
//   npx tsx src/cli/short.ts niche
//   npx tsx src/cli/short.ts lint <plan.json>
//   npx tsx src/cli/short.ts prepare <plan.json> [--flow google-flow|veoframe|higgsfield|fal]
//   npx tsx src/cli/short.ts tts <plan.json> [--force]
//   npx tsx src/cli/short.ts assemble <plan.json>
//   npx tsx src/cli/short.ts qa <plan.json>
//   npx tsx src/cli/short.ts rehearse <plan.json>     (synthetic clips, real narration; spends no video credits)
//   npx tsx src/cli/short.ts lastframe <plan.json> <clipId>   (writes clips/<clipId>-last.png, the next clip's start frame)
//   npx tsx src/cli/short.ts thumb <image> "<words>" <out.png> [A|B]

import "dotenv/config";
import fs from "fs";
import path from "path";
import { makeThumbnail } from "../media/clips";
import { rankNiches } from "../niche/scorer";
import { getProvider, listProviders } from "../providers";
import { clipOutput, writeInstructions, writeJob } from "../providers/browserWorker";
import { instructionsFor } from "../providers/instructions";
import { buildShort, runPaths } from "../shorts/assemble";
import { ff } from "../shorts/ffmpeg";
import { narrate } from "../shorts/narrate";
import { ShortPlan, parsePlan } from "../shorts/plan";
import { qaShort } from "../shorts/qa";
import { reviewPlan } from "../shorts/review";

const STORAGE = path.join(process.cwd(), "storage");

function loadPlan(file: string): ShortPlan {
  return parsePlan(JSON.parse(fs.readFileSync(path.resolve(file), "utf-8")));
}

function flag(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}
const has = (name: string) => process.argv.includes(`--${name}`);

function printReview(plan: ShortPlan): { errors: number; warnings: number } {
  const r = reviewPlan(plan);
  console.log(`\nPlan ${plan.id}: "${plan.title}" (${plan.format}, ${plan.clips.length} clips, ${plan.clips.reduce((n, c) => n + c.seconds, 0)}s)`);
  console.log(`Hook score ${r.hook.score}/100 (${r.hook.words} words, about ${r.hook.estSeconds}s, reading grade ${r.hook.readingGrade}); ${r.narrationWords} spoken words`);
  for (const area of ["hook", "prompt", "narration", "facts", "plan", "flow"] as const) {
    const items = r.findings.filter((f) => f.area === area);
    if (!items.length) continue;
    console.log(`\n${area}`);
    for (const f of items) console.log(`  ${f.level === "ok" ? "ok   " : f.level === "warn" ? "WARN " : "ERROR"} ${f.message}`);
  }
  console.log(`\nResult: ${r.errors} error(s), ${r.warnings} warning(s)`);
  return { errors: r.errors, warnings: r.warnings };
}

async function cmdPrepare(plan: ShortPlan) {
  const id = flag("flow") || plan.flow;
  const provider = getProvider(id);
  const s = provider.status();
  if (!s.ok) {
    console.log(`Flow '${id}' is not available: ${s.reason}`);
    process.exitCode = 2;
    return;
  }
  const P = runPaths(STORAGE, plan.id);
  fs.writeFileSync(path.join(P.runDir, "plan.json"), JSON.stringify(plan, null, 2));
  if (provider.kind === "browser") {
    for (const c of plan.clips.filter((x) => x.type === "ai_video")) {
      writeJob({ planId: plan.id, clipId: c.id, prompt: c.prompt, seconds: c.seconds, aspect: plan.aspect, runDir: P.runDir, referenceImage: c.referenceImage }, id);
    }
    writeInstructions(P.runDir, id, instructionsFor(id, plan));
    console.log(`Job pack written to ${path.join(P.runDir, "jobs", id)}`);
    plan.clips.filter((c) => c.type === "ai_video").forEach((c) => console.log(`  ${c.id} -> ${clipOutput(P.runDir, c.id)}`));
  } else {
    console.log(`'${id}' is an API provider; clips are generated by the pipeline run.`);
  }
}

async function cmdTts(plan: ShortPlan, force: boolean) {
  const res = await narrate(STORAGE, plan, { force });
  for (const r of res) {
    console.log(`  ${r.clipId}: ${r.seconds.toFixed(2)}s of speech, ${r.room.toFixed(2)}s available -> ${r.fits ? "fits" : "TOO LONG"}${r.skipped ? " (kept existing)" : ""}`);
    if (!r.fits) process.exitCode = 1;
  }
}

async function cmdQa(plan: ShortPlan | null, file: string, dir: string) {
  const r = await qaShort(file, plan, path.join(dir, "frames"));
  console.log(`\nQA for ${file}`);
  for (const c of r.checks) console.log(`  ${c.ok ? "ok   " : "FAIL "} ${c.id}: ${c.message}`);
  console.log(`\nFrames to inspect:\n${r.frames.map((f) => "  " + f).join("\n")}`);
  console.log(r.ok ? "\nQA PASSED" : "\nQA FAILED");
  if (!r.ok) process.exitCode = 1;
}

async function cmdRehearse(plan: ShortPlan) {
  const id = `${plan.id}-rehearsal`;
  const rp = parsePlan({ ...plan, id });
  const P = runPaths(STORAGE, id);
  const [W, H] = rp.aspect === "9:16" ? [1080, 1920] : [1920, 1080];
  const variants = [
    { w: Math.round(W * 0.667), h: Math.round(H * 0.667), audio: true },
    { w: H, h: W, audio: true },
    { w: W, h: H, audio: false },
    { w: W, h: H, audio: true },
  ];
  console.log("Creating synthetic clips with mixed sizes, frame rates and audio (matching, rotated, silent)...");
  let i = 0;
  for (const c of rp.clips.filter((x) => x.type === "ai_video")) {
    const v = variants[i % variants.length];
    const args = ["-f", "lavfi", "-i", `testsrc2=size=${v.w}x${v.h}:rate=24:duration=8`];
    if (v.audio) args.push("-f", "lavfi", "-i", `sine=frequency=${180 + i * 70}:sample_rate=44100:duration=8`);
    args.push("-c:v", "libx264", "-pix_fmt", "yuv420p", ...(v.audio ? ["-c:a", "aac"] : []), "-t", "8", clipOutput(P.runDir, c.id));
    await ff(args);
    i++;
  }
  console.log("Narration (real speech, real word timing)...");
  await cmdTts(rp, has("force"));
  console.log("Assembling...");
  const out = await buildShort(STORAGE, rp);
  console.log(`Built ${out.file} (${out.duration.toFixed(2)}s)`);
  out.warnings.forEach((w) => console.log("  note:", w));
  await cmdQa(rp, out.file, P.runDir);
}

async function main() {
  const [cmd, a, b, c, d] = process.argv.slice(2);
  if (cmd === "niche") {
    for (const n of rankNiches()) console.log(`${n.total.toFixed(2)}  ${n.name}\n       ${n.evidence}\n`);
    console.log("Providers:", JSON.stringify(listProviders()));
    return;
  }
  if (cmd === "thumb") {
    if (!a || !b || !c) throw new Error('Usage: short.ts thumb <image> "<words>" <out.png> [A|B]');
    const work = path.join(STORAGE, "shorts", "_thumbs");
    fs.mkdirSync(work, { recursive: true });
    await makeThumbnail({ image: a, text: b, out: c, variant: d === "B" ? "B" : "A", workDir: work });
    console.log("Thumbnail written to", path.resolve(c));
    return;
  }
  if (!a) throw new Error("Usage: short.ts <niche|lint|prepare|tts|assemble|qa|rehearse|thumb> <plan.json>");
  const plan = loadPlan(a);
  if (cmd === "lint") {
    process.exitCode = printReview(plan).errors ? 1 : 0;
  } else if (cmd === "prepare") {
    const r = printReview(plan);
    if (r.errors) {
      process.exitCode = 1;
      return console.log("\nFix the errors above before preparing the job pack.");
    }
    await cmdPrepare(plan);
  } else if (cmd === "tts") await cmdTts(plan, has("force"));
  else if (cmd === "assemble") {
    const r = await buildShort(STORAGE, plan);
    console.log(`Built ${r.file} (${r.duration.toFixed(2)}s); loudness before correction ${r.loudness.input_i} LUFS`);
    r.warnings.forEach((w) => console.log("  note:", w));
  } else if (cmd === "qa") {
    const P = runPaths(STORAGE, plan.id);
    await cmdQa(plan, path.join(P.final, `${plan.id}.mp4`), P.runDir);
  } else if (cmd === "rehearse") await cmdRehearse(plan);
  else if (cmd === "lastframe") {
    // The hand-off frame: attach it as the start frame of the next clip so the two shots join seamlessly.
    if (!b) throw new Error("Usage: short.ts lastframe <plan.json> <clipId>");
    const P = runPaths(STORAGE, plan.id);
    const src = path.join(P.clips, `${b}.mp4`);
    if (!fs.existsSync(src)) throw new Error(`Missing clip file: ${src}`);
    const out = path.join(P.clips, `${b}-last.png`);
    await ff(["-sseof", "-0.12", "-i", src, "-frames:v", "1", "-q:v", "1", out]);
    console.log("Last frame written to", out);
  } else throw new Error(`Unknown command '${cmd}'`);
}

main().catch((e) => {
  console.error("\nFAILED:", e instanceof Error ? e.message : e);
  process.exit(1);
});
